import { chromium } from "playwright-core"
import assert from "node:assert/strict"

const origin = process.env.REDCODE_TEST_CONSOLE_URL
const browser = await chromium.launch({ headless: true, executablePath: process.env.REDCODE_TEST_BROWSER })
try {
  const page = await browser.newPage({ viewport: { width: 1366, height: 1100 } })
  page.setDefaultTimeout(5_000)
  const errors = []
  const resourceRequests = []
  page.on("pageerror", (error) => errors.push(error.message))
  await page.route("https://coordinator.example.invalid/**", (route) => {
    resourceRequests.push(route.request().url())
    return route.abort()
  })
  const rail = page.getByRole("navigation", { name: "Console scopes", exact: true })
  const menu = page.locator("#navigation")
  const chooseScope = async (name, heading) => {
    await rail.getByRole("button", { name, exact: true }).click()
    await page.getByRole("heading", { name: heading, exact: true }).waitFor()
    assert.equal(await rail.getByRole("button", { name, exact: true }).getAttribute("aria-pressed"), "true")
  }
  const login = async (email) => {
    await page.goto(origin)
    await page.getByLabel("Email", { exact: true }).fill(email)
    await page.getByLabel("Password", { exact: true }).fill("Test123!")
    await page.getByRole("button", { name: "Sign in", exact: true }).click()
    await page.getByRole("heading", { name: "Overview", exact: true }).waitFor()
    await menu.getByRole("link", { name: "Overview", exact: true }).waitFor()
    await rail.getByRole("button", { name: "Infrastructure", exact: true }).click()
    await page.getByRole("heading", { name: "Infrastructure ownership", exact: true }).waitFor()
  }
  await login("owner@example.test")
  await page.getByText("Owner admin · infrastructure administration", { exact: true }).waitFor()
  assert.equal(await page.locator("#context").getByLabel("Organization", { exact: true }).count(), 0)
  assert.equal(await menu.getByRole("link", { name: "Invitations", exact: true }).count(), 0)
  await menu.getByRole("link", { name: "Servers & workers", exact: true }).click()
  await page.getByRole("heading", { name: "Servers & workers", exact: true }).waitFor()
  await page.getByLabel("Server or worker name", { exact: true }).fill("Browser worker")
  await page.getByLabel("Server origin (optional)", { exact: true }).fill("https://coordinator.example.invalid")
  await page.getByRole("button", { name: "Register resource", exact: true }).click()
  const row = page.getByRole("row").filter({ has: page.getByRole("cell", { name: "Browser worker", exact: true }) })
  await row.waitFor()
  const resourceID = await row.getByRole("cell").nth(1).textContent()
  await menu.getByRole("link", { name: "Workspace grants", exact: true }).click()
  await page.getByLabel("Resource ID", { exact: true }).selectOption(resourceID)
  await page.getByLabel("Workspace ID", { exact: true }).fill(process.env.REDCODE_TEST_WORKSPACE)
  await page.getByLabel("Absolute checkout directory", { exact: true }).fill("/projects/browser")
  await page.getByRole("button", { name: "Grant workspace access", exact: true }).click()
  await page.getByRole("cell", { name: "/projects/browser", exact: true }).waitFor()
  await menu.getByRole("link", { name: "Infrastructure members", exact: true }).click()
  await page.getByLabel("Account email", { exact: true }).fill("operator@example.test")
  await page.getByLabel("Infrastructure role", { exact: true }).selectOption("user")
  await page.getByRole("button", { name: "Set infrastructure role", exact: true }).click()
  await page.getByRole("cell", { name: "Owner user", exact: true }).waitFor()
  await chooseScope("Organization", "Overview")
  assert.equal(await menu.getByRole("link", { name: "Servers & workers", exact: true }).count(), 0)
  assert.equal(await menu.getByRole("link", { name: "Access keys", exact: true }).count(), 0)
  assert.equal(await page.locator("#context").getByLabel("Workspace", { exact: true }).count(), 0)
  await chooseScope("Workspace", "Access keys")
  await page.locator("#context").getByLabel("Workspace", { exact: true }).waitFor()
  assert.equal(await menu.getByRole("link", { name: "Members", exact: true }).count(), 0)
  assert.equal(await menu.getByRole("link", { name: "Tasks", exact: true }).count(), 1)
  await chooseScope("Account", "Account")
  assert.equal(await page.locator("#context select").count(), 0)
  assert.equal(await menu.getByRole("link").count(), 1)
  await page.goBack()
  await page.getByRole("heading", { name: "Access keys", exact: true }).waitFor()
  assert.equal(await rail.getByRole("button", { name: "Workspace", exact: true }).getAttribute("aria-pressed"), "true")
  await chooseScope("Organization", "Overview")
  const organizationScope = rail.getByRole("button", { name: "Organization", exact: true })
  await organizationScope.focus()
  await page.keyboard.press("ArrowDown")
  assert.equal(await page.evaluate(() => document.activeElement.getAttribute("aria-label")), "Workspace")
  await page.keyboard.press("End")
  assert.equal(await page.evaluate(() => document.activeElement.getAttribute("aria-label")), "Account")
  if (process.env.REDCODE_TEST_SCREENSHOT)
    await page.screenshot({ path: process.env.REDCODE_TEST_SCREENSHOT, fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole("button", { name: "Open sidebar panel", exact: true }).click()
  assert.equal(await page.locator("#sidebar").getAttribute("data-state"), "open")
  if (process.env.REDCODE_TEST_SCREENSHOT)
    await page.screenshot({
      path: process.env.REDCODE_TEST_SCREENSHOT.replace(/\.png$/, "-drawer.png"),
      fullPage: true,
    })
  assert.equal(await page.locator(".console-content").evaluate((node) => node.inert), true)
  assert.equal(await page.locator(".console-topbar").evaluate((node) => node.inert), true)
  await organizationScope.focus()
  await page.keyboard.press("Shift+Tab")
  assert.equal(await page.evaluate(() => document.activeElement.textContent), "Authentication settings")
  await page.keyboard.press("Tab")
  assert.equal(await page.evaluate(() => document.activeElement.getAttribute("aria-label")), "Organization")
  await page.keyboard.press("Escape")
  assert.equal(await page.locator("#sidebar").getAttribute("data-state"), "closed")
  assert.equal(await page.locator(".console-content").evaluate((node) => node.inert), false)
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  if (process.env.REDCODE_TEST_SCREENSHOT)
    await page.screenshot({
      path: process.env.REDCODE_TEST_SCREENSHOT.replace(/\.png$/, "-compact.png"),
      fullPage: true,
    })
  await page.getByRole("button", { name: "Open sidebar panel", exact: true }).click()
  await menu.getByRole("link", { name: "Members", exact: true }).click()
  await page.getByRole("heading", { name: "Members", exact: true }).waitFor()
  assert.equal(await page.locator("#sidebar").getAttribute("data-state"), "closed")
  await page.setViewportSize({ width: 1366, height: 1100 })
  await chooseScope("Infrastructure", "Infrastructure members")
  await menu.getByRole("link", { name: "Workspace grants", exact: true }).click()
  await page.getByRole("button", { name: "Revoke", exact: true }).click()
  await page.getByRole("alertdialog").getByRole("button", { name: "Revoke", exact: true }).click()
  await page.getByRole("cell", { name: "/projects/browser", exact: true }).waitFor({ state: "detached" })
  await page.getByRole("button", { name: "Sign out", exact: true }).click()
  await login("operator@example.test")
  await page.getByText("Owner user · task execution", { exact: true }).waitFor()
  assert.equal(await page.getByRole("button", { name: "Register resource", exact: true }).count(), 0)
  assert.equal(await page.getByRole("button", { name: "Set infrastructure role", exact: true }).count(), 0)
  assert.equal(await page.getByRole("button", { name: "Grant workspace access", exact: true }).count(), 0)
  assert.equal(await menu.getByRole("link", { name: "Infrastructure members", exact: true }).count(), 0)
  assert.equal(await menu.getByRole("link", { name: "Workspace grants", exact: true }).count(), 0)
  assert.equal(await menu.getByRole("link", { name: "Global authentication", exact: true }).count(), 0)
  assert.equal(await menu.getByRole("link", { name: "Owner authentication", exact: true }).count(), 0)
  await page.goto(origin + "/#operators")
  await page.waitForURL((url) => url.hash === "#infrastructure")
  await page.getByRole("heading", { name: "Infrastructure ownership", exact: true }).waitFor()
  assert.equal(new URL(page.url()).hash, "#infrastructure")
  await chooseScope("Organization", "Overview")
  assert.equal(await menu.getByRole("link", { name: "Invitations", exact: true }).count(), 0)
  assert.equal(await menu.getByRole("link", { name: "Authentication settings", exact: true }).count(), 0)
  await chooseScope("Workspace", "Access keys")
  await menu.getByRole("link", { name: "Tasks", exact: true }).click()
  await page.getByText("No execution resource assigned", { exact: true }).waitFor()
  assert.deepEqual(resourceRequests, [])
  await page.getByRole("button", { name: "Sign out", exact: true }).click()
  await page.getByRole("heading", { name: "Welcome to your Console", exact: true }).waitFor()
  assert.equal(await rail.isVisible(), false)
  assert.deepEqual(errors, [])
} finally {
  await browser.close()
}
