import { chromium } from "playwright-core"
import assert from "node:assert/strict"

const origin = process.env.REDCODE_TEST_CONSOLE_URL
const browser = await chromium.launch({ headless: true, executablePath: process.env.REDCODE_TEST_BROWSER })
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
  const errors = []
  page.on("pageerror", (error) => errors.push(error.message))
  await page.goto(origin)
  if (process.env.REDCODE_TEST_AUTH_SETTINGS) {
    await page.getByLabel("Setup code", { exact: true }).fill("setup-code")
    await page.getByLabel("Your name", { exact: true }).fill("Owner")
    await page.getByLabel("Email", { exact: true }).fill("owner@example.test")
    await page.getByLabel("Password (at least 8 characters)", { exact: true }).fill("Test123!")
    await page.getByLabel("Organization name", { exact: true }).fill("First")
    await page.getByRole("button", { name: "Create Console", exact: true }).click()
    await page.getByRole("heading", { name: "Set up sign-in · optional", exact: true }).waitFor()
    await page.getByRole("button", { name: "Save Console URL", exact: true }).click()
    await page.getByRole("button", { name: "Add identity provider", exact: true }).click()
    const modal = page.getByRole("dialog")
    await modal.getByLabel("Provider name", { exact: true }).fill("Realm 0")
    await modal.getByLabel("Issuer URL", { exact: true }).fill(process.env.REDCODE_TEST_ISSUER)
    await modal.getByLabel("Client ID", { exact: true }).fill("redcode")
    await modal.getByLabel("Client secret", { exact: true }).fill("disposable-oidc-test-client-secret")
    await modal.getByLabel("Status", { exact: true }).selectOption("Enabled")
    await modal.getByRole("button", { name: "Add identity provider", exact: true }).click()
    await page.getByRole("button", { name: "Test Realm 0", exact: true }).click()
    await page.getByRole("status").filter({ hasText: "OIDC discovery succeeded" }).waitFor()
    await page.getByRole("button", { name: "Edit Realm 0", exact: true }).click()
    assert.equal(await modal.getByLabel("Client secret", { exact: true }).inputValue(), "")
    await modal.getByRole("button", { name: "Edit identity provider", exact: true }).click()
    await page.getByRole("button", { name: "Continue to Console", exact: true }).waitFor()
    if (process.env.REDCODE_TEST_SCREENSHOT)
      await page.screenshot({ path: process.env.REDCODE_TEST_SCREENSHOT, fullPage: true })
    await page.getByRole("button", { name: "Continue to Console", exact: true }).click()
    await page.getByRole("heading", { name: "Overview", exact: true }).waitFor()
    await page.getByRole("button", { name: "Sign out", exact: true }).click()
  }
  await page.getByRole("button", { name: "Sign in with Realm 0", exact: true }).waitFor()
  await page.getByLabel("Email", { exact: true }).fill("owner@example.test")
  await page.getByLabel("Password", { exact: true }).fill("Test123!")
  await page.getByRole("button", { name: "Sign in", exact: true }).click()
  await page.getByRole("heading", { name: "Overview", exact: true }).waitFor()
  await page.goto(origin + "/#account")
  await page.getByRole("button", { name: "Link Realm 0", exact: true }).click()
  await page.getByRole("heading", { name: "Overview", exact: true }).waitFor()
  assert(!page.url().includes("federation="))
  await page.goto(origin + "/#account")
  await page.getByRole("cell", { name: "Realm 0", exact: true }).waitFor()
  const control = page.getByRole("button", { name: "Link Realm 0", exact: true })
  assert(await control.getAttribute("class"))
  if (process.env.REDCODE_TEST_SCREENSHOT && !process.env.REDCODE_TEST_AUTH_SETTINGS)
    await page.screenshot({ path: process.env.REDCODE_TEST_SCREENSHOT, fullPage: true })
  await page.getByRole("button", { name: "Sign out", exact: true }).click()
  await page.getByRole("button", { name: "Sign in with Realm 0", exact: true }).click()
  await page.getByRole("heading", { name: "Overview", exact: true }).waitFor()
  assert(!page.url().includes("token"))
  assert.deepEqual(errors, [])
} finally {
  await browser.close()
}
