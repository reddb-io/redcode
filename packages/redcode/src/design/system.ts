/**
 * What this project already looks like.
 *
 * A prototype is only useful if what the user sees is what they would get, and the prompt's "find
 * the design system and use it" is an instruction the model follows unevenly. So the facts are
 * gathered once and handed over: which framework, which tokens, which fonts, which pages to read.
 * Nothing is evaluated — every fact is read as text — and nothing is guessed: a fact that is not
 * in the repository is not in the summary.
 *
 * The person owns the result. A `DESIGN.md` in the project (open-design's convention) or a
 * `.red/DESIGN.md` is believed as-is and no scan runs; when neither exists the scan writes the
 * second one, and from then on editing it is how the summary is corrected.
 */

/** Looked up from the directory upward, first match wins. */
export const FILES = ["DESIGN.md", ".red/DESIGN.md"] as const
export const GENERATED = ".red/DESIGN.md"
export const HEADER = "<!-- generated by redcode design mode; edit freely, it will not be overwritten -->"

/** Enough to be a reminder, not a second system prompt. */
export const MAX_CHARS = 3_000
export const MAX_TOKENS = 40

export interface PackageJson {
  readonly dependencies?: Record<string, string>
  readonly devDependencies?: Record<string, string>
}

export interface Facts {
  /** Framework and styling libraries, as "name version" strings. */
  readonly stack: readonly string[]
  /** Where the tokens came from, relative to the directory. */
  readonly tokensFile?: string
  /** `--name: value` pairs, capped. */
  readonly tokens: readonly string[]
  readonly fonts: readonly string[]
  /** Paths the model should read before drawing. */
  readonly pages: readonly string[]
  /** A design document already in the repo: path and its first lines. */
  readonly doc?: { readonly path: string; readonly excerpt: string }
  /** Tailwind v3 config path, when one exists. */
  readonly tailwindConfig?: string
  /** shadcn's `components.json`, when one exists. */
  readonly shadcn?: string
}

